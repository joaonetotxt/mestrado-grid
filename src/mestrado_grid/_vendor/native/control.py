"""Stop predicate and exact disk paging for native context objects."""
from collections import OrderedDict
from pathlib import Path
import gzip, pickle, hashlib

def feasible(result,expected=96):
    return (result.get('status')=='feasible' and result.get('approved_cases')==expected
        and result.get('expected_cases')==expected and result.get('failed_cases')==0
        and result.get('normalized_violation')==0
        and bool(result.get('normalized_violations'))
        and all(v==0 for v in result['normalized_violations'].values()))

def under_target(result,target=30000000.):
    import math
    if not feasible(result):return False
    m=result.get('metrics') or {}
    v=m.get('selection_objective',float('inf'))
    return m.get('financial_policy')=='CASTRO_ALIGNED_ANNUAL_WEIGHTED_v1' and math.isfinite(v) and v<target

class Proxy:
    def __init__(self,owner,number):
        object.__setattr__(self,'_owner',owner);object.__setattr__(self,'number',number)
    def __getattr__(self,name):return getattr(object.__getattribute__(self,'_owner').get(object.__getattribute__(self,'number')),name)
    def __setattr__(self,name,value):setattr(self._owner.get(self.number),name,value)

class Pickler(pickle.Pickler):
    def __init__(self,f,shared):super().__init__(f,protocol=5);self.shared=shared
    def persistent_id(self,obj):
        for name,value in self.shared.items():
            if obj is value:return ('shared',name)
        return None

class Unpickler(pickle.Unpickler):
    def __init__(self,f,shared):super().__init__(f);self.shared=shared
    def persistent_load(self,pid):
        if pid[0]!='shared' or pid[1] not in self.shared:raise ValueError('Unknown shared context object')
        return self.shared[pid[1]]

class DiskContexts:
    """List-compatible proxies. Iterating context numbers never loads big objects.

    Files are generated by this process only; hashes are checked before loading.
    Native RNG state and all evaluated records are serialized without alteration.
    """
    def __init__(self,path,shared=None,capacity=4):
        self.path=Path(path);self.path.mkdir(exist_ok=True)
        self.shared=shared or {};self.capacity=capacity;self.live=OrderedDict();self.proxies=[];self.hashes={}
    def __len__(self):return len(self.proxies)
    def __iter__(self):return iter(self.proxies)
    def __getitem__(self,index):return self.proxies[index]
    def save(self,n):
        p=self.path/f'{n:06d}.pkl.gz';tmp=p.with_suffix('.tmp')
        with gzip.open(tmp,'wb',compresslevel=1) as f:Pickler(f,self.shared).dump(self.live[n])
        tmp.replace(p);self.hashes[n]=hashlib.sha256(p.read_bytes()).hexdigest()
    def trim(self):
        while len(self.live)>self.capacity:
            n=next(iter(self.live));self.save(n);del self.live[n]
    def append(self,obj):
        n=len(self.proxies);assert obj.number==n
        self.live[n]=obj;self.proxies.append(Proxy(self,n));self.trim()
    def get(self,n):
        if n not in self.live:
            p=self.path/f'{n:06d}.pkl.gz'
            assert hashlib.sha256(p.read_bytes()).hexdigest()==self.hashes[n], 'Context file changed'
            with gzip.open(p,'rb') as f:self.live[n]=Unpickler(f,self.shared).load()
            self.trim()
        self.live.move_to_end(n);return self.live[n]
    def flush(self):
        for n in list(self.live):self.save(n)
